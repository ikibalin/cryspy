"""Single crystal integrated intensities of FullProf (Cry = 1, Irf = 4) and
CrysPy.

FullProf refines the squared structure factors F² of the reflection file
(.int) with ``F²obs = Sc · y · F²calc``; CrysPy calculates the unpolarized
intensity of a ``diffrn`` experiment as ``scale · (I+ + I-) = 2 scale · y ·
F²``, so the scale of CrysPy is half the scale of FullProf. Both use the
magnetic scattering length 0.2695 · 10^-12 cm per μB.

Converted: nuclear phases (Jbt = 0) and magnetic phases (Jbt = 1) given by
basis functions for every symmetry operator (Isy = -2), one or several
propagation vectors, the isotropic extinction of FullProf (Ext-Model 1,
y = (1 + 0.001 Ext1 F² λ³ / sin 2θ)^(-1/2)) as the model ``qani`` of
CrysPy with ``q_ij`` proportional to the metric tensor. The magnetic phase
becomes a crystal with the superspace group P1(abg)0 (msCIF categories):
every atom generated by the operators of FullProf is an atom of CrysPy and
its Fourier component is ``Mcos + i Msin = f S exp(2 pi i k.r)`` (f = 1
when 2k is a reciprocal lattice vector, 2 otherwise; r is the position
generated by the operator before the reduction to the first cell, as
FullProf takes it).

Refused: flipping ratios (itypdata = 2), several phases, other magnetic
descriptions (Isy != -2, Jbt != 0, 1), form factors other than <j0>
(``M`` types). Values that cannot be kept give a warning.
"""
